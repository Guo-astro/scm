"use strict";

// Generator for the renderer bridge + its contract doc (ts-migration Tier 2).
//
//   node scripts/gen-bridge.js          # write preload.js + docs/ipc-contract.md
//   node scripts/gen-bridge.js --check  # exit 1 when either committed file is stale
//
// preload.js is emitted through the local prettier (same config as
// `bun run format`), so the committed file always passes `format:check`.
// Byte-stability is enforced by test/ipc-bridge.test.js: committed file ===
// generatePreload(). Never hand-edit preload.js or docs/ipc-contract.md —
// edit scripts/bridge-table.mjs and regenerate.

const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const PRELOAD = path.join(ROOT, "preload.js");
const DOC = path.join(ROOT, "docs", "ipc-contract.md");

const PRELOAD_HEADER = `// @ts-check
"use strict";

// GENERATED FILE — do not edit by hand. Edit scripts/bridge-table.mjs, then
// run \`node scripts/gen-bridge.js\`. test/ipc-bridge.test.js fails when this
// file drifts from the table.
//
// Single-file CommonJS by design: this preload runs with \`sandbox: true\`
// (see main/ipc/protocol.js), so it cannot require() any project module —
// "electron" is the only allowed require. Type drift is caught instead by
// the \`@type {MemoriesBridge}\` annotation below: MemoriesBridge
// (src/types.d.ts) owns every signature, so a param/return change there
// fails \`tsc\` here, and a missing/extra method fails \`tsc\` too.

/** @typedef {import("./src/types").MemoriesBridge} MemoriesBridge */

const { contextBridge, ipcRenderer, webUtils } = require("electron");

/** @type {MemoriesBridge} */
const memories = {
`;

/**
 * @param {import("./bridge-table.mjs").BridgeEntry} entry
 * @returns {string}
 */
function emitEntry(entry) {
	switch (entry.kind) {
		case "invoke": {
			const args = [JSON.stringify(entry.channel), ...entry.params].join(", ");
			return `\t${entry.method}: (${entry.params.join(", ")}) => ipcRenderer.invoke(${args}),`;
		}
		case "send":
			return `\t${entry.method}: (${entry.params.join(", ")}) => ipcRenderer.send(${JSON.stringify(entry.channel)}, ${entry.payload}),`;
		case "local":
			return `\t${entry.method}: (${entry.params.join(", ")}) => webUtils.${entry.localFn}(${entry.params.join(", ")}),`;
		case "push":
			return [
				`\t${entry.method}: (callback) => {`,
				"\t\t/**",
				'\t\t * @param {import("electron").IpcRendererEvent} _event',
				`\t\t * @param {${entry.payloadType}} payload`,
				"\t\t */",
				"\t\tconst listener = (_event, payload) => callback(payload);",
				`\t\tipcRenderer.on(${JSON.stringify(entry.channel)}, listener);`,
				`\t\treturn () => ipcRenderer.removeListener(${JSON.stringify(entry.channel)}, listener);`,
				"\t},",
			].join("\n");
		default:
			throw new Error(`gen-bridge: unknown kind: ${entry.kind}`);
	}
}

async function generatePreload() {
	const { BRIDGE } = await import("./bridge-table.mjs");
	const body = BRIDGE.map(emitEntry).join("\n");
	const code = `${PRELOAD_HEADER}${body}\n};\n\ncontextBridge.exposeInMainWorld("memories", memories);\n`;
	const prettier = await import("prettier");
	// format() does not load config files on its own — resolve .prettierrc
	// explicitly (same config `bun run format` uses) so the emitted file is
	// format:check-clean and byte-stable across prettier invocations.
	const config = await prettier.resolveConfig(PRELOAD);
	return await prettier.format(code, { ...(config ?? {}), filepath: PRELOAD });
}

async function generateDoc() {
	const { BRIDGE } = await import("./bridge-table.mjs");
	const handles = BRIDGE.filter((e) => e.kind === "invoke").length;
	const sends = BRIDGE.filter((e) => e.kind === "send");
	const ons = sends.length;
	const pushes = BRIDGE.filter((e) => e.kind === "push");
	const locals = BRIDGE.filter((e) => e.kind === "local");
	const rows = BRIDGE.map((e, i) => {
		const channel = e.channel ? `\`${e.channel}\`` : "—";
		const method = `\`${e.method}(${e.params.join(", ")})\``;
		const owner = e.kind === "push" ? e.handler : `\`${e.handler}\``;
		// The failure contract is invoke-only: a push has no reply, and a
		// send is fire-and-forget.
		const failure = e.kind === "invoke" ? `\`${e.failure}\`` : "—";
		return `| ${i + 1} | ${channel} | ${e.kind} | ${method} | ${owner} | ${failure} |`;
	});
	const failures = BRIDGE.filter((e) => e.kind === "invoke").reduce(
		(acc, e) => {
			acc[e.failure] = (acc[e.failure] || 0) + 1;
			return acc;
		},
		{},
	);
	const v2 = BRIDGE.filter(
		(e) =>
			e.kind === "invoke" &&
			["throws", "mixed", "bare-ok", "empty", "null"].includes(e.failure),
	).length;
	return [
		"# IPC contract (generated)",
		"",
		"Generated by `node scripts/gen-bridge.js` from `scripts/bridge-table.mjs` —",
		"do not edit by hand. Where `preload.js`, this snapshot, the channels",
		"registered at main-process load, or `MemoriesBridge` drift apart,",
		"`bun run test:ipc-bridge` fails with the specific mismatch.",
		"",
		`- \`ipcMain.handle\`: ${handles} · \`ipcMain.on\`: ${ons} (${sends.map((e) => `\`${e.channel}\``).join(", ")})`,
		`- preload bridge: ${handles} invoke + ${ons} send + ${pushes.length} push + ${locals.length} local (\`getPathForFile\`)`,
		"",
		"## Failure contract",
		"",
		"How a failed invoke surfaces to the renderer. The uniform-envelope",
		"migration (the `ipc-wrapper.ts` V2) needs this catalogue: a channel",
		"whose failure is indistinguishable from a successful empty result",
		"(`empty`, `null`, `bare-ok`) or that throws past the boundary",
		"(`throws`) cannot be read by the renderer at all.",
		"",
		`- shapes in use: ${Object.entries(failures)
			.map(([k, v]) => `\`${k}\` ${v}`)
			.join(" · ")}`,
		`- channels the renderer cannot read a failure from (V2 migration list): **${v2}**`,
		"",
		"| # | Channel | Kind | Preload method | Main-side owner | Failure |",
		"|---|---------|------|----------------|-----------------|---------|",
		...rows,
		"",
	].join("\n");
}

async function main() {
	const check = process.argv.includes("--check");
	const results = [
		[PRELOAD, await generatePreload()],
		[DOC, await generateDoc()],
	];
	let stale = false;
	for (const [file, content] of results) {
		const current = fs.existsSync(file) ? fs.readFileSync(file, "utf8") : null;
		if (current === content) continue;
		stale = true;
		if (check) {
			console.error(
				`[gen-bridge] STALE: ${path.relative(ROOT, file)} — run: node scripts/gen-bridge.js`,
			);
		} else {
			fs.writeFileSync(file, content);
			console.log(`[gen-bridge] wrote ${path.relative(ROOT, file)}`);
		}
	}
	if (stale && check) process.exit(1);
	if (!stale) console.log("[gen-bridge] up to date");
}

module.exports = { generatePreload, generateDoc };

if (require.main === module) {
	main().catch((err) => {
		console.error(err);
		process.exit(1);
	});
}
